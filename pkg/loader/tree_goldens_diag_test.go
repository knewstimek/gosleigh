// runTreeGhidra builds an x86-32 function from prog bytes and runs the faithful
// universal-action tree (BuildUniversalAction + SetCurrent("decompile")), returning
// the Ghidra-format C output. Mirrors buildGcd but for arbitrary bytes.
func runTreeGhidra(t *testing.T, prog []byte) string {
	t.Helper()
	_, file, _, ok := runtime.Caller(1)
	if !ok {
		t.Fatal("runtime.Caller failed")
	}
	dir := filepath.Dir(file)
	slaPath := filepath.Join(dir, "../sla/testdata/x86-packed.sla")
	pspecPath := filepath.Join(dir, "../../testdata/sla/x86.pspec")
	engine, base, err := (&loader.EngineBuilder{SLAPath: slaPath, PspecPath: pspecPath, Bytes: prog}).Build()
	if err != nil {
		t.Fatalf("Build: %v", err)
	}
	result, err := bridge.Build(engine, bridge.BuildConfig{Name: "entry", Entry: base, MaxInstructions: 60})
	if err != nil {
		t.Fatalf("bridge.Build: %v", err)
	}
	fd := result.Funcdata
	db := pcode.NewActionDatabase()
	db.BuildUniversalAction(nil)
	db.BuildDefaultGroups()
	act := db.SetCurrent("decompile")
	act.Perform(fd)
	out, err := pcode.NewPrintC().
		SetRegisterNames(engine.RegisterNamesByLocation()).
		SetProcessEntry("processEntry", 2).
		SetGhidraFormat().
		Emit(fd)
	if err != nil {
		t.Fatalf("PrintC: %v", err)
	}
	return out
}

// TestTreeGoldensDiag (TREE_DIAG=1) runs the universal-action tree against each
// x86-32 golden and reports match/mismatch, to gauge how close the tree is to
// replacing the 41-call production subset. Diagnostic only -- logs diffs, never fails.
func TestTreeGoldensDiag(t *testing.T) {
	if os.Getenv("TREE_DIAG") == "" {
		t.Skip("set TREE_DIAG=1 to run")
	}
	cases := []struct {
		prog      []byte
		goldenKey string
		name      string
	}{
		{[]byte{0x55, 0x8B, 0xEC, 0x83, 0xEC, 0x08, 0xC7, 0x45, 0xF8, 0x00, 0x00, 0x00, 0x00, 0xC7, 0x45, 0xFC, 0x00, 0x00, 0x00, 0x00, 0xEB, 0x09, 0x8B, 0x45, 0xFC, 0x83, 0xC0, 0x01, 0x89, 0x45, 0xFC, 0x83, 0x7D, 0xFC, 0x05, 0x7D, 0x0B, 0x8B, 0x4D, 0xF8, 0x03, 0x4D, 0xFC, 0x89, 0x4D, 0xF8, 0xEB, 0xE6, 0x8B, 0x45, 0xF8, 0x8B, 0xE5, 0x5D, 0xC3}, "counted_loop_x86_32", "counted_loop"},
		{[]byte{0x55, 0x8B, 0xEC, 0x51, 0xC7, 0x45, 0xFC, 0x00, 0x00, 0x00, 0x00, 0x83, 0x7D, 0x08, 0x00, 0x74, 0x16, 0x8B, 0x45, 0x08, 0x8B, 0x4D, 0xFC, 0x03, 0x08, 0x89, 0x4D, 0xFC, 0x8B, 0x55, 0x08, 0x8B, 0x42, 0x04, 0x89, 0x45, 0x08, 0xEB, 0xE4, 0x8B, 0x45, 0xFC, 0x8B, 0xE5, 0x5D, 0xC3}, "sum_list_x86_32", "sum_list"},
		{[]byte{0x55, 0x8B, 0xEC, 0x83, 0x7D, 0x08, 0x00, 0x7D, 0x07, 0x8B, 0x45, 0x08, 0xF7, 0xD8, 0xEB, 0x03, 0x8B, 0x45, 0x08, 0x5D, 0xC3}, "abs_ifelse_x86_32", "abs_val"},
		{[]byte{0x55, 0x8B, 0xEC, 0x83, 0x7D, 0x08, 0x00, 0x7E, 0x18, 0x8B, 0x45, 0x0C, 0x3B, 0x45, 0x08, 0x7E, 0x09, 0xB8, 0x02, 0x00, 0x00, 0x00, 0xEB, 0x0B, 0xEB, 0x07, 0xB8, 0x01, 0x00, 0x00, 0x00, 0xEB, 0x02, 0x33, 0xC0, 0x5D, 0xC3}, "nested_if_x86_32", "classify2"},
		{[]byte{0x8b, 0x4c, 0x24, 0x08, 0x8b, 0x44, 0x24, 0x04, 0x85, 0xc9, 0x74, 0x0b, 0x99, 0xf7, 0xf9, 0x8b, 0xc1, 0x8b, 0xca, 0x85, 0xd2, 0x75, 0xf5, 0xc3}, "gcd_x86_32", "gcd"},
	}
	pass := 0
	for _, c := range cases {
		got := strings.TrimSpace(runTreeGhidra(t, c.prog))
		want := strings.TrimSpace(loadGhidraGolden(t, c.goldenKey))
		if got == want {
			pass++
			t.Logf("[TREE %s] MATCH", c.name)
		} else {
			t.Logf("[TREE %s] MISMATCH\n--- WANT ---\n%s\n--- GOT ---\n%s", c.name, want, got)
		}
	}
	t.Logf("TREE goldens: %d/%d byte-identical", pass, len(cases))
}
